function withLanguageInHref(href, lang) {
  if (!href) return href;
  const trimmed = href.trim();
  if (!trimmed || trimmed === '#') return href;
  if (trimmed.startsWith('#')) return href;
  if (trimmed.startsWith('mailto:') || trimmed.startsWith('tel:') || trimmed.startsWith('javascript:') || trimmed.startsWith('data:')) return href;
  if (trimmed.startsWith('//') || /^[a-z][a-z\d+\-.]*:/i.test(trimmed)) return href;

  const hashIndex = trimmed.indexOf('#');
  const hashPart = hashIndex >= 0 ? trimmed.slice(hashIndex) : '';
  const withoutHash = hashIndex >= 0 ? trimmed.slice(0, hashIndex) : trimmed;
  const queryIndex = withoutHash.indexOf('?');
  const pathPart = queryIndex >= 0 ? withoutHash.slice(0, queryIndex) : withoutHash;
  const queryPart = queryIndex >= 0 ? withoutHash.slice(queryIndex + 1) : '';

  if (!/\.html$/i.test(pathPart)) return href;

  const params = new URLSearchParams(queryPart);
  if (lang === DEFAULT_LANG) {
    params.delete('lang');
  } else {
    params.set('lang', lang);
  }

  const nextQuery = params.toString();
  return `${pathPart}${nextQuery ? `?${nextQuery}` : ''}${hashPart}`;
}

function syncInternalLanguageLinks(lang) {
  document.querySelectorAll('a[href]').forEach((link) => {
    const original = link.getAttribute('href');
    if (!original) return;
    const nextHref = withLanguageInHref(original, lang);
    if (nextHref !== original) {
      link.setAttribute('href', nextHref);
    }
  });
}

function syncLanguageInUrl(lang) {
  const url = new URL(window.location.href);
  if (lang === DEFAULT_LANG) {
    url.searchParams.delete('lang');
  } else {
    url.searchParams.set('lang', lang);
  }
  const nextUrl = `${url.pathname}${url.search}${url.hash}`;
  window.history.replaceState({}, '', nextUrl);
}

