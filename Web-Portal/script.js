function openNewsModal(idx) {
  const lang = ((document.documentElement.getAttribute('lang') || 'de').toLowerCase() === 'en') ? 'en' : 'de';
  const details = lang === 'en' ? newsDetailsEn : newsDetails;
  const visuals = lang === 'en' ? newsVisualsEn : newsVisuals;
  const modal = document.getElementById('news-modal');
  const body = document.getElementById('news-modal-body');
  const visual = visuals[idx] || visuals[0];
  if (!modal || !body) return;
  body.innerHTML = `
    <article class="news-detail-card">
      <div class="news-detail-hero" style="background-image: linear-gradient(135deg, rgba(10, 16, 24, 0.55), rgba(10, 16, 24, 0.15)), url('${visual.image}')">
        <span class="news-detail-badge">${visual.badge}</span>
      </div>
      <div class="news-detail-content">
        ${details[idx] || (lang === 'en' ? '<h2>Article</h2><p>Content is being updated.</p>' : '<h2>Beitrag</h2><p>Inhalte werden aktualisiert.</p>')}
      </div>
    </article>
  `;
  modal.style.display = 'flex';
  document.body.style.overflow = 'hidden';
  setTimeout(() => modal.classList.add('active'), 10);
}

function closeNewsModal() {
  const modal = document.getElementById('news-modal');
  if (!modal) return;
  modal.classList.remove('active');
  setTimeout(() => {
    modal.style.display = 'none';
    document.body.style.overflow = '';
  }, 220);
}

document.addEventListener('DOMContentLoaded', () => {
  const modal = document.getElementById('news-modal');
  if (!modal) return;
  modal.addEventListener('click', (event) => {
    if (event.target === modal) closeNewsModal();
  });
  document.addEventListener('keydown', (event) => {
    if (modal.style.display === 'flex' && (event.key === 'Escape' || event.key === 'Esc')) {
      closeNewsModal();
    }
  });
});

