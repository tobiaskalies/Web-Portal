function normalizeLanguage(value) {
  if (!value) return null;
  const normalized = value.toLowerCase();
  return SUPPORTED_LANGS.includes(normalized) ? normalized : null;
}

function getLanguageFromUrl() {
  const params = new URLSearchParams(window.location.search);
  return normalizeLanguage(params.get('lang'));
}

function resolveLanguage() {
  const fromUrl = getLanguageFromUrl();
  const fromStorage = normalizeLanguage(localStorage.getItem('lang'));
  return fromUrl || fromStorage || DEFAULT_LANG;
}

function setText(selector, value) {
  if (!value) return;
  document.querySelectorAll(selector).forEach((el) => {
    el.textContent = value;
  });
}

function setTextAt(selector, index, value) {
  if (!value) return;
  const items = document.querySelectorAll(selector);
  if (items[index]) {
    items[index].textContent = value;
  }
}

function setTextList(selector, values, lang) {
  const items = document.querySelectorAll(selector);
  items.forEach((el, idx) => {
    if (!el.dataset.deText) {
      el.dataset.deText = el.textContent || '';
    }
    if (lang === 'en') {
      if (values[idx]) el.textContent = values[idx];
    } else {
      el.textContent = el.dataset.deText;
    }
  });
}

function setHtmlList(selector, values, lang) {
  const items = document.querySelectorAll(selector);
  items.forEach((el, idx) => {
    if (!el.dataset.deHtml) {
      el.dataset.deHtml = el.innerHTML;
    }
    if (lang === 'en') {
      if (values[idx]) el.innerHTML = values[idx];
    } else {
      el.innerHTML = el.dataset.deHtml;
    }
  });
}

function setAttrList(selector, attr, values, lang) {
  const items = document.querySelectorAll(selector);
  const storeAttr = `data-i18n-orig-${attr.replace(/[^a-z0-9_-]/gi, '-').toLowerCase()}`;
  items.forEach((el, idx) => {
    if (!el.hasAttribute(storeAttr)) {
      el.setAttribute(storeAttr, el.getAttribute(attr) || '');
    }
    if (lang === 'en') {
      if (values[idx]) el.setAttribute(attr, values[idx]);
    } else {
      el.setAttribute(attr, el.getAttribute(storeAttr) || '');
    }
  });
}

